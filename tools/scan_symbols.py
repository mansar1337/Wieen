#!/usr/bin/env python3
"""Recover the Luau entry points of the Roblox client Sober is running.

The client is a stripped Android x86-64 shared object, so the only way to
name its functions is to match them against an upstream Luau build: both are
compiled from the same sources, so the functions keep their relative order
and their sizes.

Inside one copy of the VM the sizes match exactly, so the matcher anchors on
a run of functions with identical sizes and then extends the match forward
and backward.  The image contains the Luau VM more than once; every copy is
listed and the agent picks the one it observes being called.

Usage:
    scan_symbols.py [--apk <split apk>] [--out src/agent/luau_symbols.h]
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LUAU = REPO / "work/luau-src/build-rel"

DEFAULT_APK = (Path.home() / ".var/app/org.vinegarhq.Sober/data/sober/packages/x86_64/"
               "com.roblox.client/split_config.x86_64.apk")

WANTED = {
    "_Z12luau_compilePKcmP18lua_CompileOptionsPm": "LUA_COMPILE",
    "_Z9luau_loadP9lua_StatePKcS2_mi": "LUA_LOAD",
    "_Z9lua_pcallP9lua_Stateiii": "LUA_PCALL",
    "_Z12lua_getfieldP9lua_StateiPKc": "LUA_GETFIELD",
    "_Z10lua_gettopP9lua_State": "LUA_GETTOP",
    "_Z10lua_settopP9lua_Statei": "LUA_SETTOP",
    "_Z13lua_tolstringP9lua_StateiPm": "LUA_TOLSTRING",
    "_Z8lua_typeP9lua_Statei": "LUA_TYPE",
    "_ZL12luau_executeILb0EEvP9lua_State": "LUA_INTERPRETER",
}

OBJECTS = [
    ("lapi.cpp.o", ("LUA_PCALL", "LUA_GETFIELD", "LUA_GETTOP", "LUA_SETTOP",
                    "LUA_TOLSTRING", "LUA_TYPE")),
    ("lvmload.cpp.o", ("LUA_LOAD",)),
    ("lcode.cpp.o", ("LUA_COMPILE",)),
    ("lvmexecute.cpp.o", ("LUA_INTERPRETER",)),
]

HEADER = """/*
 * Luau entry points inside the Roblox client image.
 *
 * Generated by tools/scan_symbols.py - do not edit by hand.
 *
 * The client ships the Luau VM more than once; every copy is listed and the
 * agent picks the one it observes being called.
 */
#ifndef WIEEN_LUAU_SYMBOLS_H
#define WIEEN_LUAU_SYMBOLS_H

"""

SEED = 100       # functions that must match to accept a copy
WINDOW_SIZE = 0x400000    # align within a 4 MiB window
WINDOW_STEP = 0x100000    # and slide the window by 1 MiB
LOOKAHEAD = 20000  # how far to look for the next function of the right size


def extract_client(apk: Path, out: Path) -> Path:
    if not apk.exists():
        raise SystemExit(f"APK not found: {apk}")
    with zipfile.ZipFile(apk) as z:
        names = [n for n in z.namelist() if n.endswith("libroblox.so")]
        if not names:
            raise SystemExit("libroblox.so not in the APK")
        out.write_bytes(z.read(names[0]))
    return out


def eh_functions(so: Path) -> list[tuple[int, int]]:
    out = subprocess.run(["readelf", "--debug-dump=frames", str(so)],
                         capture_output=True, text=True).stdout
    funcs = []
    for m in re.finditer(r"FDE cie=\S+ pc=([0-9a-f]+)\.\.([0-9a-f]+)", out):
        lo, hi = int(m.group(1), 16), int(m.group(2), 16)
        funcs.append((lo, hi - lo))
    funcs.sort()
    return funcs


def obj_functions(obj: Path) -> list[tuple[int, int, str]]:
    out = subprocess.run(["nm", "-S", "--defined-only", str(obj)],
                         capture_output=True, text=True).stdout
    funcs = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in "tT":
            funcs.append((int(parts[0], 16), int(parts[1], 16), parts[3]))
    funcs.sort()
    return funcs


def align(target: list[tuple[int, int]], ref: list[tuple[int, int, str]],
          pool: list[int] | None = None):
    """Needleman-Wunsch over the function sizes.

    Returns (mapping, used_target_indices).  The alignment is global, so
    unlike a greedy walk it does not commit to a same-sized function that
    happens to appear earlier.
    """
    n, m = len(ref), len(target)
    if n == 0 or m == 0:
        return {}, []

    def close(a: int, b: int) -> float:
        if a == b:
            return 1.0
        mx = max(a, b)
        return max(0.0, 1.0 - abs(a - b) / mx) if mx else 1.0

    gap = -1.2
    dp = [[0.0] * (m + 1) for _ in range(n + 1)]
    for i in range(1, n + 1):
        dp[i][0] = dp[i - 1][0] + gap
    for j in range(1, m + 1):
        dp[0][j] = dp[0][j - 1] + gap
    for i in range(1, n + 1):
        ri = ref[i - 1][1]
        row = dp[i]
        prev = dp[i - 1]
        for j in range(1, m + 1):
            sim = 2.0 * close(ri, target[j - 1][1]) - 0.8
            best = prev[j - 1] + sim
            if prev[j] + gap > best:
                best = prev[j] + gap
            if row[j - 1] + gap > best:
                best = row[j - 1] + gap
            row[j] = best

    i, j = n, m
    pairs = []
    while i > 0 and j > 0:
        ri = ref[i - 1][1]
        sim = 2.0 * close(ri, target[j - 1][1]) - 0.8
        if abs(dp[i][j] - (dp[i - 1][j - 1] + sim)) < 1e-9:
            pairs.append((ref[i - 1][2], j - 1))
            i, j = i - 1, j - 1
        elif dp[i][j] == dp[i - 1][j] + gap:
            i -= 1
        else:
            j -= 1
    pairs.reverse()
    mapping = {name: target[idx][0] for name, idx in pairs}
    used = [idx for _, idx in pairs]
    return mapping, used


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apk", type=Path, default=DEFAULT_APK)
    ap.add_argument("--so", type=Path, default=REPO / "work/libs/libroblox.so")
    ap.add_argument("--out", type=Path, default=REPO / "src/agent/luau_symbols.h")
    args = ap.parse_args()

    if not args.so.exists():
        extract_client(args.apk, args.so)
        print(f"extracted the client from {args.apk}")

    target = eh_functions(args.so)
    print(f"client functions: {len(target)}")

    refs = {}
    for obj, _ in OBJECTS:
        path = LUAU / "x" / obj
        if not path.exists():
            print(f"missing {path} - build the reference Luau first")
            return 1
        refs[obj] = obj_functions(path)

    copies = []
    seen: set[tuple] = set()
    image = target[-1][0] + target[-1][1] if target else 0
    for win_lo in range(0, max(1, image), WINDOW_STEP):
        win_hi = win_lo + WINDOW_SIZE
        pool = [i for i, (a, sz) in enumerate(target)
                if win_lo <= a < win_hi]
        if len(pool) < 200:
            continue
        mapping, _ = align([target[i] for i in pool], refs["lapi.cpp.o"])
        if len(mapping) < 100:
            continue
        copy = {WANTED[n]: off for n, off in mapping.items() if n in WANTED}
        if len(copy) < 6:
            continue
        if any(v == 0 for v in copy.values()):
            continue
        key = (copy["LUA_PCALL"], copy["LUA_GETTOP"], copy["LUA_GETFIELD"])
        if key in seen:
            continue
        seen.add(key)

        lo = min(mapping.values())
        hi = max(mapping.values())
        for obj, names in OBJECTS:
            if obj == "lapi.cpp.o":
                continue
            opool = [i for i, (a, sz) in enumerate(target)
                     if lo - 0x400000 <= a <= hi + 0x400000]
            sub, _ = align([target[i] for i in opool], refs[obj])
            for n, off in sub.items():
                if n in WANTED and WANTED[n] in names:
                    cur = copy.get(WANTED[n])
                    if cur is None or abs(cur - lo) > abs(off - lo):
                        copy[WANTED[n]] = off
        copies.append((copy, lo, hi))

    if not copies:
        print("no Luau copy found")
        return 1

    lines = [HEADER]
    for idx, (copy, lo, hi) in enumerate(copies):
        lines.append("struct wieen_luau_copy\n{\n")
        for key in sorted(WANTED.values()):
            lines.append(f"    unsigned long {key.lower()};\n")
        lines.append("};\n")
        lines.append(f"static const struct wieen_luau_copy LUA_COPY_{idx} = {{\n")
        for key in sorted(WANTED.values()):
            lines.append(f"    0x{copy.get(key, 0):X}UL, /* {key} */\n")
        lines.append("};\n\n")
    names = ", ".join(f"LUA_COPY_{i}" for i in range(len(copies)))
    lines.append(f"static const struct wieen_luau_copy* const WIEEN_LUAU_COPIES[] = {{ {names} }};\n")
    lines.append(f"#define WIEEN_LUAU_COPY_COUNT {len(copies)}\n")
    lines.append("\n#endif /* WIEEN_LUAU_SYMBOLS_H */\n")
    args.out.write_text("".join(lines))
    print(f"wrote {args.out}: {len(copies)} Luau copies")
    for idx, (copy, lo, hi) in enumerate(copies):
        print(f"  copy {idx}: 0x{lo:x}-0x{hi:x}  " +
              " ".join(f"{k}=0x{copy.get(k, 0):x}" for k in sorted(WANTED.values())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
