#!/usr/bin/env python3
"""Recover the Luau entry points of the Roblox client Sober is running.

The client is a stripped Android x86-64 shared object, so the only way to
name its functions is to align them against an upstream Luau build: both
are compiled from the same sources, so the functions keep their relative
order and their sizes.

The alignment is a Needleman-Wunsch over the function sizes of both
binaries, which is precise enough to identify every entry point (the
matching sizes are usually exact).

Usage:
    scan_symbols.py [--apk <split apk>] [--out src/agent/luau_symbols.h]
"""
from __future__ import annotations

import argparse
import json
import os
import re
import struct
import subprocess
import sys
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LUAU = REPO / "work/luau-src/build-rel"

DEFAULT_APK = (Path.home() / ".var/app/org.vinegarhq.Sober/data/sober/packages/x86_64/"
               "com.roblox.client/split_config.x86_64.apk")

# the Luau API we need inside the client
WANTED = {
    "_Z12luau_compilePKcmP18lua_CompileOptionsPm": "API_LUA_COMPILE",
    "_Z9luau_loadP9lua_StatePKcS2_mi": "API_LUA_LOAD",
    "_Z9lua_pcallP9lua_Stateiii": "API_LUA_PCALL",
    "_Z12lua_getfieldP9lua_StateiPKc": "API_LUA_GETFIELD",
    "_Z10lua_gettopP9lua_State": "API_LUA_GETTOP",
    "_Z10lua_settopP9lua_Statei": "API_LUA_SETTOP",
    "_Z13lua_tolstringP9lua_StateiPm": "API_LUA_TOLSTRING",
    "_Z8lua_typeP9lua_Statei": "API_LUA_TYPE",
    "_Z12lua_mainthreadP9lua_State": "API_LUA_MAINTHREAD",
    "_Z12luau_executeP9lua_State": "API_LUA_EXECUTE",
    "_ZL12luau_executeILb0EEvP9lua_State": "API_LUA_INTERPRETER",
}

HEADER = """/*
 * Luau entry points inside the Roblox client image.
 *
 * Generated by tools/scan_symbols.py - do not edit by hand.
 */
#ifndef WIEEN_LUAU_SYMBOLS_H
#define WIEEN_LUAU_SYMBOLS_H

"""


def extract_client(apk: Path, out: Path) -> Path:
    if not apk.exists():
        raise SystemExit(f"APK not found: {apk}")
    with zipfile.ZipFile(apk) as z:
        names = [n for n in z.namelist() if n.endswith("libroblox.so")]
        if not names:
            raise SystemExit("libroblox.so not in the APK")
        out.write_bytes(z.read(names[0]))
    return out


def eh_functions(so: Path) -> list[tuple[int, int]]:
    """Function ranges from .eh_frame."""
    out = subprocess.run(["readelf", "--debug-dump=frames", str(so)],
                         capture_output=True, text=True).stdout
    funcs = []
    for m in re.finditer(r"FDE cie=\S+ pc=([0-9a-f]+)\.\.([0-9a-f]+)", out):
        lo, hi = int(m.group(1), 16), int(m.group(2), 16)
        funcs.append((lo, hi - lo))
    funcs.sort()
    return funcs


def obj_functions(obj: Path) -> list[tuple[int, int, str]]:
    out = subprocess.run(["nm", "-S", "--defined-only", str(obj)],
                         capture_output=True, text=True).stdout
    funcs = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 4 and parts[2] in "tT":
            funcs.append((int(parts[0], 16), int(parts[1], 16), parts[3]))
    funcs.sort()
    return funcs


def align(target: list[tuple[int, int]], ref: list[tuple[int, int, str]]):
    """Needleman-Wunsch over function sizes."""
    n, m = len(ref), len(target)

    def close(a, b):
        if a == b:
            return 1.0
        mx = max(a, b)
        return max(0.0, 1.0 - abs(a - b) / mx) if mx else 1.0

    gap = -1.2
    dp = [[0.0] * (m + 1) for _ in range(n + 1)]
    for i in range(1, n + 1):
        dp[i][0] = dp[i - 1][0] + gap
    for j in range(1, m + 1):
        dp[0][j] = dp[0][j - 1] + gap
    for i in range(1, n + 1):
        ri = ref[i - 1][1]
        for j in range(1, m + 1):
            sim = 2.0 * close(ri, target[j - 1][1]) - 0.8
            dp[i][j] = max(dp[i - 1][j - 1] + sim, dp[i - 1][j] + gap, dp[i][j - 1] + gap)
    i, j = n, m
    pairs = []
    while i > 0 and j > 0:
        ri = ref[i - 1][1]
        sim = 2.0 * close(ri, target[j - 1][1]) - 0.8
        if abs(dp[i][j] - (dp[i - 1][j - 1] + sim)) < 1e-9:
            pairs.append((ref[i - 1], target[j - 1], close(ri, target[j - 1][1])))
            i, j = i - 1, j - 1
        elif dp[i][j] == dp[i - 1][j] + gap:
            i -= 1
        else:
            j -= 1
    pairs.reverse()
    return pairs


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apk", type=Path, default=DEFAULT_APK)
    ap.add_argument("--so", type=Path, default=REPO / "work/libs/libroblox.so")
    ap.add_argument("--out", type=Path, default=REPO / "src/agent/luau_symbols.h")
    args = ap.parse_args()

    if not args.so.exists():
        extract_client(args.apk, args.so)
        print(f"extracted the client from {args.apk}")

    target = eh_functions(args.so)
    print(f"client functions: {len(target)}")

    found = {}
    for obj in ("lapi.cpp.o", "lvmload.cpp.o", "lcode.cpp.o", "lvmexecute.cpp.o"):
        path = LUAU / "x" / obj
        if not path.exists():
            print(f"missing {path} - build the reference Luau first (make -C work/luau-src)")
            return 1
        ref = obj_functions(path)
        for r, t, score in align(target, ref):
            if r[2] in WANTED and score >= 0.85:
                found.setdefault(WANTED[r[2]], (t[0], score, r[2]))

    missing = [v for v in WANTED.values() if v not in found]
    lines = [HEADER]
    for name, (off, score, sym) in sorted(found.items()):
        lines.append(f"#define {name} 0x{off:X}UL /* {sym} ({score:.2f}) */\n")
    lines.append("\n#endif /* WIEEN_LUAU_SYMBOLS_H */\n")
    args.out.write_text("".join(lines))
    print(f"wrote {args.out}")
    for name, (off, score, sym) in sorted(found.items()):
        print(f"  {name:<22} 0x{off:x}  ({sym}, {score:.2f})")
    if missing:
        print(f"not found: {', '.join(sorted(set(missing)))}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
