#!/usr/bin/env python3
"""Turn a binary file into a C header with the bytes in it.

    bin2h.py <file> <name>

writes the header to stdout, so the build can redirect it into a file.
"""
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    path, name = sys.argv[1], sys.argv[2]
    with open(path, "rb") as f:
        data = f.read()
    print("/* generated by tools/bin2h.py - do not edit */")
    print(f"static const unsigned char {name}[] = {{")
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        print("    " + "".join(f"0x{b:02x}, " for b in chunk))
    print("};")
    print(f"static const unsigned long {name}_size = {len(data)}UL;")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
